import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

test('photo library HTTP access, project isolation, pagination and automatic new report collection', { skip: process.env.RUN_PHOTO_LIBRARY_DB_TESTS !== '1', timeout: 120000 }, async () => {
  const database = `delta_photo_test_${randomUUID().replaceAll('-', '')}`;
  process.env.MONGO_URI = `mongodb://127.0.0.1:27017/${database}`;
  process.env.JWT_SECRET = randomUUID();
  const scratch = await fs.mkdtemp(path.join(os.tmpdir(), 'delta-photo-'));
  process.env.UPLOADS_DIR = path.join(scratch, 'uploads');
  process.env.VAPID_PUBLIC_KEY = ''; process.env.VAPID_PRIVATE_KEY = ''; process.env.SMTP_HOST = '';
  const mongoose = (await import('mongoose')).default;
  const express = (await import('express')).default;
  const jwt = (await import('jsonwebtoken')).default;
  const routes = (await import('../src/presentation/routes/index.js')).default;
  const { errorHandler } = await import('../src/presentation/middlewares/errorHandler.js');
  const { UserModel } = await import('../src/infrastructure/db/models/UserModel.js');
  const { WorkReportModel } = await import('../src/infrastructure/db/models/WorkReportModel.js');
  await mongoose.connect(process.env.MONGO_URI, { serverSelectionTimeoutMS: 5000 });
  let server;
  try {
    const user = await UserModel.create({ fullName: 'Photo fixture', email: 'photo@fixture.test', role: 'TECHNICAL_STAFF', active: true, passwordHash: 'fixture' });
    const other = await UserModel.create({ fullName: 'Other fixture', email: 'other@fixture.test', role: 'TECHNICAL_STAFF', active: true, passwordHash: 'fixture' });
    const report = (owner, name, images) => ({ user: owner._id, employeeName: owner.fullName, projectName: name, details: 'fixture only', images });
    const images = Array.from({ length: 65 }, (_, i) => ({ publicUrl: `/uploads/photo-fixture-${i}.jpg`, mimeType: 'image/jpeg' }));
    await WorkReportModel.create(report(user, 'مشروع الصور', images));
    await WorkReportModel.create(report(other, 'مشروع سري', [{ publicUrl: '/uploads/secret.jpg', mimeType: 'image/jpeg' }]));
    const app = express(); app.use(express.json()); app.use('/api', routes); app.use(errorHandler);
    server = app.listen(0, '127.0.0.1'); await new Promise((resolve) => server.once('listening', resolve));
    const base = `http://127.0.0.1:${server.address().port}/api/work-reports/photo-library`;
    const token = jwt.sign({ sub: String(user._id), role: user.role }, process.env.JWT_SECRET);
    const get = (query = '') => fetch(base + query, { headers: { Authorization: `Bearer ${token}` } });
    assert.equal((await fetch(base)).status, 401);
    const response = await get(); assert.equal(response.status, 200);
    assert.equal(response.headers.get('cache-control'), 'private, no-store');
    let data = await response.json(); assert.equal(data.folders.length, 1); assert.equal(data.folders[0].photoCount, 65); assert.equal(data.folders[0].photos, undefined);
    const query = `?folder=${encodeURIComponent(data.folders[0].key)}`;
    data = await (await get(query)).json(); assert.equal(data.album.photos.length, 60); assert.equal(data.album.pages, 2);
    data = await (await get(query + '&page=2')).json(); assert.equal(data.album.photos.length, 5);
    assert.equal((await get('?folder=' + encodeURIComponent('name:مشروع سري'))).status, 404);
    await WorkReportModel.create(report(user, 'مشروع الصور', [{ publicUrl: '/uploads/new-photo.jpg', mimeType: 'image/jpeg' }]));
    data = await (await get()).json(); assert.equal(data.folders.length, 1); assert.equal(data.folders[0].photoCount, 66); assert.equal(data.folders[0].reportCount, 2);
    const source = data.folders[0].key;
    const manager = await UserModel.create({ fullName: 'Photo manager', email: 'manager@fixture.test', role: 'GENERAL_MANAGER', active: true, passwordHash: 'fixture' });
    const managerToken = jwt.sign({ sub: String(manager._id), role: manager.role }, process.env.JWT_SECRET);
    const post = (endpoint, body, auth = managerToken) => fetch(base + endpoint, { method: 'POST', headers: { Authorization: `Bearer ${auth}`, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    const readManager = async (suffix = '') => (await fetch(base + suffix, { headers: { Authorization: `Bearer ${managerToken}` } })).json();
    const original = await WorkReportModel.findOne({ user: user._id, 'images.64': { $exists: true } }).lean();
    await WorkReportModel.create(report(manager, 'مجلد الوجهة', [{ publicUrl: '/uploads/target.jpg', mimeType: 'image/jpeg' }]));
    const current = await readManager(query);
    const firstId = current.album.photos[0].id;
    assert.equal((await post('/organize', { folder: source, ids: [firstId], action: 'DELETE' }, token)).status, 403);
    assert.equal((await post('/organize', { folder: source, ids: ['foreign'], action: 'DELETE' })).status, 409);
    const target = (await readManager()).folders.find((f) => f.name === 'مجلد الوجهة').key;
    assert.equal((await post('/organize', { folder: source, ids: [firstId], action: 'MOVE', targetFolder: target })).status, 200);
    assert.equal((await readManager(query)).album.photoCount, 65);
    const targetQuery = '?folder=' + encodeURIComponent(target);
    assert.equal((await readManager(targetQuery)).album.photoCount, 2);
    assert.equal((await post('/organize', { folder: target, ids: [firstId], action: 'DELETE' })).status, 200);
    assert.equal((await readManager(targetQuery)).album.photoCount, 1);
    const retained = await WorkReportModel.findById(original._id).lean();
    assert.deepEqual(retained.images, original.images);
    // A refreshed library must not reimport a deleted or moved image.
    assert.equal((await readManager(query)).album.photos.some((p) => p.id === firstId), false);
    const remaining = (await readManager(query)).album;
    for (const image of images) await fs.writeFile(path.join(process.env.UPLOADS_DIR, path.basename(image.publicUrl)), Buffer.from('original-image-bytes'));
    const archiveResponse = await post('/download', { folder: source, all: true });
    assert.equal(archiveResponse.status, 200); assert.equal(archiveResponse.headers.get('content-type'), 'application/zip');
    const unzipper = (await import('unzipper')).default;
    const archive = await unzipper.Open.buffer(Buffer.from(await archiveResponse.arrayBuffer()));
    assert.equal(archive.files.length, 65);
    assert.deepEqual(await archive.files[0].buffer(), Buffer.from('original-image-bytes'));
    const partial = await post('/download', { folder: source, ids: [remaining.photos[0].id] });
    assert.equal((await unzipper.Open.buffer(Buffer.from(await partial.arrayBuffer()))).files.length, 1);
    await fs.writeFile(path.join(scratch, 'outside.jpg'), 'outside-private-file');
    await WorkReportModel.create(report(manager, 'مسار غير صالح', [{ publicUrl: '/uploads/../outside.jpg', mimeType: 'image/jpeg' }]));
    const unsafe = (await readManager()).folders.find((f) => f.name === 'مسار غير صالح');
    assert.equal((await post('/download', { folder: unsafe.key, all: true })).status, 400);
    assert.equal((await post('/organize', { folder: source, all: true, excludedIds: [remaining.photos[0].id], action: 'DELETE' })).status, 200);
    assert.equal((await readManager(query)).album.photoCount, 1);
    assert.equal((await WorkReportModel.findById(original._id)).images.length, 65);
    assert.equal((await fs.readFile(path.join(process.env.UPLOADS_DIR, 'photo-fixture-0.jpg'))).toString(), 'original-image-bytes');
    assert.equal((await post('/folders', { name: 'مجلد جديد' }, token)).status, 403);
    assert.equal((await post('/folders', { name: '../غير صالح' })).status, 400);
    assert.equal((await post('/folders', { name: '   ' })).status, 400);
    const createdFolder = await post('/folders', { name: '  مجلد   جديد ' });
    assert.equal(createdFolder.status, 201);
    const custom = (await createdFolder.json()).folder;
    assert.equal(custom.name, 'مجلد جديد');
    assert.equal((await readManager()).folders.find((f) => f.key === custom.key).photoCount, 0);
    assert.equal((await post('/folders', { name: 'مجلد جديد' })).status, 409);
    const targetPhotos = (await readManager(targetQuery)).album.photos;
    assert.equal((await post('/organize', { folder: target, ids: [targetPhotos[0].id], action: 'MOVE', targetFolder: custom.key })).status, 200);
    const customQuery = '?folder=' + encodeURIComponent(custom.key);
    assert.equal((await readManager(customQuery)).album.photoCount, 1);
    assert.equal((await post('/folders/delete', { folder: custom.key }, token)).status, 403);
    assert.equal((await post('/folders/delete', { folder: custom.key })).status, 200);
    assert.equal((await readManager()).folders.some((f) => f.key === custom.key), false);
    const stillOriginal = await WorkReportModel.findOne({ projectName: 'مجلد الوجهة' });
    assert.equal(stillOriginal.images.length, 1);
    assert.equal((await post('/folders', { name: custom.name })).status, 201);
    assert.equal((await readManager(customQuery)).album.photoCount, 0);
    assert.equal((await post('/folders/delete', { folder: custom.key })).status, 200);
    assert.equal((await post('/folders/delete', { folder: source })).status, 200);
    assert.equal((await readManager()).folders.some((f) => f.key === source), false);
    await WorkReportModel.create(report(user, 'مشروع الصور', [{ publicUrl: '/uploads/future-photo.jpg', mimeType: 'image/jpeg' }]));
    assert.equal((await readManager()).folders.some((f) => f.key === source), false);
    assert.equal((await post('/folders', { name: 'مشروع الصور' })).status, 201);
    assert.equal((await readManager(query)).album.photoCount, 1);
    assert.equal((await WorkReportModel.findById(original._id)).images.length, 65);
    assert.equal((await post('/folders/delete', { folder: 'name:unknown-folder' })).status, 404);
  } finally {
    if (server) { server.closeAllConnections(); await new Promise((resolve) => server.close(resolve)); }
    assert.match(mongoose.connection.name, /^delta_photo_test_[a-f0-9]{32}$/);
    await mongoose.connection.dropDatabase(); await mongoose.disconnect();
    assert.ok(path.basename(scratch).startsWith('delta-photo-'));
    await fs.rm(scratch, { recursive: true, force: true });
  }
});
